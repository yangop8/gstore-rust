//! The result and baseline format `gstore-bench/1`.
//!
//! A run writes one [`BenchResult`]: the environment, the machine
//! calibration, the workload (generator version, data hash, query text
//! hashes) and one [`BackendRun`] per storage layout with the build, open,
//! query, update and concurrency phases. A baseline is the same document with
//! `kind = "baseline"` (see `gstore-bench bless`). Times are milliseconds,
//! memory MiB, sizes bytes; content hashes are 16 hex digits. Fields a phase
//! did not measure are `null`.

use std::collections::BTreeMap;
use std::path::Path;

use serde::{Deserialize, Serialize};

use crate::calib::Calibration;
use crate::workload::WorkloadSpec;

pub const SCHEMA: &str = "gstore-bench/1";

/// A complete result (or baseline) file.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BenchResult {
    /// Always [`SCHEMA`].
    pub schema: String,
    /// `result` or `baseline`.
    pub kind: String,
    /// A baseline recorded on a busy machine, to be re-blessed.
    #[serde(default)]
    pub provisional: bool,
    #[serde(default)]
    pub note: Option<String>,
    /// The profile the run used (`micro`, `smoke`, `reference`, or `custom`).
    pub profile: String,
    pub created_unix: u64,
    pub env: EnvInfo,
    #[serde(default)]
    pub calibration: Option<Calibration>,
    pub workload: WorkloadInfo,
    pub runs: Vec<BackendRun>,
}

/// Where and how the run happened.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct EnvInfo {
    pub tool_version: String,
    #[serde(default)]
    pub git_commit: Option<String>,
    #[serde(default)]
    pub git_dirty: Option<bool>,
    #[serde(default)]
    pub hostname: Option<String>,
    pub os: String,
    pub arch: String,
    pub nproc: usize,
    #[serde(default)]
    pub cpu_model: Option<String>,
    #[serde(default)]
    pub mem_total_mib: Option<u64>,
    /// Load averages when the run started.
    #[serde(default)]
    pub loadavg: Option<[f64; 3]>,
    /// Whether the harness itself is a debug build.
    #[serde(default)]
    pub debug_build: bool,
}

/// The workload: what was generated and which queries ran.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct WorkloadInfo {
    pub spec: WorkloadSpec,
    /// `lubm-like` or `tiny`.
    pub id: String,
    /// The generator version (`lubm-like/1`).
    pub version: String,
    pub lines: u64,
    pub unique_triples: u64,
    pub bytes: u64,
    pub data_fnv64: String,
    pub queries: Vec<QueryInfo>,
    #[serde(default)]
    pub chunk: Option<ChunkInfo>,
    /// Generation time when the data was (re)generated by this run.
    #[serde(default)]
    pub gen_ms: Option<f64>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct QueryInfo {
    pub name: String,
    pub text_fnv64: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ChunkInfo {
    pub unique_triples: u64,
    pub fnv64: String,
}

/// The binaries and settings one backend run used (runs merged from several
/// invocations keep their own).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct RunConfig {
    /// gstore features the harness was built with (`rocksdb`).
    #[serde(default)]
    pub features: Vec<String>,
    /// Where `gbuild` was taken from.
    #[serde(default)]
    pub bin_dir: Option<String>,
    /// `cli` (the real `gbuild`) or `lib` (test fallback: the library build).
    #[serde(default)]
    pub builder: String,
    #[serde(default)]
    pub git_commit: Option<String>,
    /// `--env K=V` given to every phase.
    #[serde(default)]
    pub env: BTreeMap<String, String>,
    /// `--gbuild-arg` values.
    #[serde(default)]
    pub gbuild_args: Vec<String>,
    /// Warm query repetitions (per query process).
    #[serde(default)]
    pub reps: usize,
    /// Fresh processes the query phase ran in (0 in files written before
    /// this field existed, meaning one).
    #[serde(default)]
    pub query_procs: usize,
    /// Whether the page cache was dropped before the first open.
    #[serde(default)]
    pub drop_caches: bool,
    /// The calibration score of the invocation that measured this run.
    #[serde(default)]
    pub calib_score_ms: Option<f64>,
}

/// One storage layout's measurements.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BackendRun {
    /// `snapshot`, `disk` or `rocksdb`.
    pub backend: String,
    #[serde(default)]
    pub config: RunConfig,
    #[serde(default)]
    pub build: Option<BuildResult>,
    #[serde(default)]
    pub open: Option<OpenResult>,
    #[serde(default)]
    pub queries: Vec<QueryMeasure>,
    /// Memory of the query child after the last query.
    #[serde(default)]
    pub query_mem: Option<MemInfo>,
    #[serde(default)]
    pub update: Option<UpdateResult>,
    #[serde(default)]
    pub conc: Option<ConcResult>,
    /// Retry attempts per phase (`check`'s targeted retries); absent = 1.
    #[serde(default)]
    pub attempts: BTreeMap<String, u32>,
}

impl BackendRun {
    pub fn new(backend: &str) -> BackendRun {
        BackendRun {
            backend: backend.to_string(),
            config: RunConfig::default(),
            build: None,
            open: None,
            queries: Vec::new(),
            query_mem: None,
            update: None,
            conc: None,
            attempts: BTreeMap::new(),
        }
    }

    pub fn query(&self, name: &str) -> Option<&QueryMeasure> {
        self.queries.iter().find(|q| q.name == name)
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct BuildResult {
    /// Wall time of the `gbuild` process.
    pub wall_ms: f64,
    /// Its peak RSS (`getrusage(RUSAGE_CHILDREN)`).
    #[serde(default)]
    pub peak_rss_mib: Option<f64>,
    /// Apparent size of the database directory (without gbuild's
    /// `parse_error.log`, which names the source path).
    pub dir_bytes: u64,
    /// Size of each top-level entry of the directory.
    #[serde(default)]
    pub files: BTreeMap<String, u64>,
    /// The command line (program and arguments).
    #[serde(default)]
    pub command: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct OpenResult {
    /// The first open after the build (cold when `cold`).
    pub first_ms: f64,
    /// Median of the warm opens (each in a fresh process).
    pub warm_ms: f64,
    #[serde(default)]
    pub warm_samples_ms: Vec<f64>,
    /// The page cache was dropped before the first open.
    #[serde(default)]
    pub cold: bool,
    #[serde(default)]
    pub rss_after_open_mib: Option<f64>,
    #[serde(default)]
    pub hwm_after_open_mib: Option<f64>,
    pub triple_num: u64,
    pub entity_num: u64,
    pub literal_num: u64,
    pub predicate_num: u64,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct QueryMeasure {
    pub name: String,
    pub rows: u64,
    pub rows_fnv64: String,
    /// The first run after open (the minimum over the query processes).
    pub first_ms: f64,
    /// The median of the warm runs of one process, the minimum over the
    /// query processes (see `proc_medians_ms`).
    pub median_ms: f64,
    /// Every warm run, of every query process.
    #[serde(default)]
    pub runs_ms: Vec<f64>,
    /// The warm median of each query process, in order. Each process draws
    /// its own hash seeds and heap layout, which moves some query times by up
    /// to ~1.5x from one process to the next but hardly within one.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub proc_medians_ms: Vec<f64>,
    /// Every run returned the same rows.
    #[serde(default = "yes")]
    pub stable: bool,
}

fn yes() -> bool {
    true
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct MemInfo {
    #[serde(default)]
    pub rss_mib: Option<f64>,
    #[serde(default)]
    pub hwm_mib: Option<f64>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct UpdateResult {
    /// Single-triple INSERT DATA statements run (and deleted again).
    pub singles: usize,
    #[serde(default)]
    pub single_insert_median_ms: Option<f64>,
    #[serde(default)]
    pub single_insert_p95_ms: Option<f64>,
    #[serde(default)]
    pub single_delete_median_ms: Option<f64>,
    #[serde(default)]
    pub single_delete_p95_ms: Option<f64>,
    /// Every single insert added one triple and every delete removed it.
    pub singles_ok: bool,
    pub chunk_triples: u64,
    pub chunk_insert_ms: f64,
    pub chunk_delete_ms: f64,
    /// `triple_num` grew by exactly the chunk's unique triples, and shrank
    /// back by as many.
    pub chunk_delta_ok: bool,
    /// Every query answers as before the updates.
    pub answers_unchanged: bool,
    #[serde(default)]
    pub mismatched: Vec<String>,
    pub checkpoint_ms: f64,
    pub reopen_ms: f64,
    pub reopen_triple_num: u64,
    /// The reopened database holds the original triple count.
    pub reopen_ok: bool,
    /// Dictionary growth (report-only: deleted terms may stay allocated).
    pub entities_before: u64,
    pub entities_after: u64,
    pub literals_before: u64,
    pub literals_after: u64,
}

impl UpdateResult {
    /// Whether every exact check of the phase held.
    pub fn round_trip_ok(&self) -> bool {
        self.singles_ok && self.chunk_delta_ok && self.answers_unchanged && self.reopen_ok
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct ConcResult {
    pub points: Vec<ConcPoint>,
    /// Within each endpoint and query every response body was identical.
    pub bodies_equal: bool,
    #[serde(default)]
    pub hwm_mib: Option<f64>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct ConcPoint {
    /// `sparql` (the single-database `Server`, GET /sparql, TSV) or `api`
    /// (the multi-database `ApiServer`, GET /api operation=query, JSON).
    pub endpoint: String,
    pub query: String,
    pub clients: usize,
    pub ok: u64,
    pub http_errors: u64,
    /// Connections the server closed (keep-alive limit), retried.
    pub reconnects: u64,
    pub secs: f64,
    pub qps: f64,
    pub mean_ms: f64,
    pub p95_ms: f64,
    pub distinct_bodies: usize,
    pub body_fnv64: String,
}

impl BenchResult {
    pub fn run(&self, backend: &str) -> Option<&BackendRun> {
        self.runs.iter().find(|r| r.backend == backend)
    }

    pub fn run_mut(&mut self, backend: &str) -> Option<&mut BackendRun> {
        self.runs.iter_mut().find(|r| r.backend == backend)
    }

    /// Read and validate a result or baseline file.
    pub fn load(path: &Path) -> Result<BenchResult, String> {
        let text = std::fs::read_to_string(path)
            .map_err(|e| format!("cannot read {}: {e}", path.display()))?;
        let r: BenchResult = serde_json::from_str(&text)
            .map_err(|e| format!("{} is not a gstore-bench result: {e}", path.display()))?;
        if r.schema != SCHEMA {
            return Err(format!(
                "{}: schema '{}' is not {SCHEMA}",
                path.display(),
                r.schema
            ));
        }
        Ok(r)
    }

    /// Write as pretty JSON (parent directories are created).
    pub fn save(&self, path: &Path) -> Result<(), String> {
        if let Some(p) = path.parent() {
            if !p.as_os_str().is_empty() {
                std::fs::create_dir_all(p)
                    .map_err(|e| format!("cannot create {}: {e}", p.display()))?;
            }
        }
        let mut text = serde_json::to_string_pretty(self).map_err(|e| e.to_string())?;
        text.push('\n');
        let tmp = path.with_extension("json.tmp");
        std::fs::write(&tmp, text).map_err(|e| format!("cannot write {}: {e}", tmp.display()))?;
        std::fs::rename(&tmp, path).map_err(|e| format!("cannot write {}: {e}", path.display()))
    }

    /// The calibration score that measured `run` (its own, else the file's).
    pub fn calib_score(&self, run: &BackendRun) -> Option<f64> {
        run.config
            .calib_score_ms
            .or_else(|| self.calibration.as_ref().map(|c| c.score_ms))
            .filter(|s| *s > 0.0)
    }
}
