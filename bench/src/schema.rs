#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct UpdateResult {
    /// Single-triple INSERT DATA statements run (and deleted again).
    pub singles: usize,
    #[serde(default)]
    pub single_insert_median_ms: Option<f64>,
    #[serde(default)]
    pub single_insert_p95_ms: Option<f64>,
    #[serde(default)]
    pub single_delete_median_ms: Option<f64>,
    #[serde(default)]
    pub single_delete_p95_ms: Option<f64>,
    /// Every single insert added one triple and every delete removed it.
    pub singles_ok: bool,
    pub chunk_triples: u64,
    pub chunk_insert_ms: f64,
    pub chunk_delete_ms: f64,
    /// `triple_num` grew by exactly the chunk's unique triples, and shrank
    /// back by as many.
    pub chunk_delta_ok: bool,
    /// Every query answers as before the updates.
    pub answers_unchanged: bool,
    #[serde(default)]
    pub mismatched: Vec<String>,
    pub checkpoint_ms: f64,
    pub reopen_ms: f64,
    pub reopen_triple_num: u64,
    /// The reopened database holds the original triple count.
    pub reopen_ok: bool,
    /// Dictionary growth (report-only: deleted terms may stay allocated).
    pub entities_before: u64,
    pub entities_after: u64,
    pub literals_before: u64,
    pub literals_after: u64,
}

impl UpdateResult {
    /// Whether every exact check of the phase held.
    pub fn round_trip_ok(&self) -> bool {
        self.singles_ok && self.chunk_delta_ok && self.answers_unchanged && self.reopen_ok
    }
}

